/**
 * Copies the ABIs produced by `forge build` into packages/sdk/src/abis.ts (typed `as const` for viem).
 * Run after changing a contract:  npm run build:contracts && npm run abis
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'contracts', 'out');

const contracts: Array<[exportName: string, file: string, name: string]> = [
  ['rutliAccountAbi', 'RutliAccount.sol', 'RutliAccount'],
  ['rutliFactoryAbi', 'RutliFactory.sol', 'RutliFactory'],
  ['rutliPaymasterAbi', 'RutliPaymaster.sol', 'RutliPaymaster'],
  ['entryPointAbi', 'EntryPoint.sol', 'EntryPoint'],
  ['mockUsdcAbi', 'MockUSDC.sol', 'MockUSDC'],
  ['helvetiaYieldVaultAbi', 'HelvetiaYieldVault.sol', 'HelvetiaYieldVault'],
  ['scamAirdropAbi', 'ScamAirdrop.sol', 'ScamAirdrop'],
];

let ts = `// AUTO-GENERATED by scripts/gen-abis.ts from contracts/out — do not edit by hand.\n\n`;
for (const [exportName, file, name] of contracts) {
  const artifact = JSON.parse(readFileSync(join(out, file, `${name}.json`), 'utf8'));
  ts += `export const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(root, 'packages', 'sdk', 'src', 'abis.ts'), ts);
console.log(`wrote packages/sdk/src/abis.ts (${contracts.length} ABIs)`);
